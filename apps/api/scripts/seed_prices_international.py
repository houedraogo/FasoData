async def seed():
    engine  = create_async_engine(settings.database_url, echo=False)
    factory = async_sessionmaker(engine, expire_on_commit=False)

    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)

    async with factory() as session:
        # Nettoyage — uniquement les données internationales
        await session.execute(
            delete(PriceData).where(
                PriceData.country.in_(["MLI", "NER"]),
                PriceData.source == "wfp",
            )
        )
        await session.commit()

        records: list[PriceData] = []

        for country_code, country_info in INTERNATIONAL_DATA.items():
            for commodity, (data, quality_label, quality) in country_info["commodities"].items():
                for (y, m), price in data.items():
                    records.append(PriceData(
                        country    = country_code,
                        commodity  = commodity,
                        region     = "National",
                        price      = float(price),
                        price_date = date(y, m, 15),
                        source     = "wfp",
                        quality    = quality,
                        notes      = f"WFP VAM / FEWS NET — {country_info['name']} · {quality_label} — moy. mensuelle {country_info['capital']}",
                    ))

        session.add_all(records)
        await session.commit()

        # Rapport
        print(f"\n✅ {len(records)} relevés insérés — données internationales WFP/FEWS NET\n")
        for country_code, country_info in INTERNATIONAL_DATA.items():
            n = sum(len(data) for _, (data, _, _) in country_info["commodities"].items())
            print(f"  {country_code} ({country_info['name']}) : {n} relevés · {len(country_info['commodities'])} produits · jan 2020 → mars 2025")

        print(f"\n  Contexte reflété :")
        print(f"  • Mali  (MLI) : Instabilité sécuritaire 2021-2022 → hausse soutenue")
        print(f"  • Niger (NER) : Coup d'état juillet 2023 → embargo CEDEAO → pic historique août-sept 2023")

    await engine.dispose()


if __name__ == "__main__":
    asyncio.run(seed())
